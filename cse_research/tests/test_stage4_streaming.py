def test_sse_manager_snapshot_on_connect():
    """Verify newly registered client immediately receives a full snapshot."""
    async def _run():
        test_bus = EventBus()
        config = IngestionConfig(sse_buffer_size=50)
        manager = SSEManager(config=config, event_bus=test_bus)

        client = await manager.register_client(ip="127.0.0.1")
        assert client.queue.qsize() == 1
        event = client.queue.get_nowait()
        assert event.event_type == "snapshot"
        assert "aspi_value" in event.data
        assert event.seq >= 1

        await manager.deregister_client(client)
        assert manager.active_connection_count == 0

    asyncio.run(_run())


def test_sse_manager_tick_diffing():
    """Verify validated snapshot values emit a 'tick' with ONLY changed fields."""
    async def _run():
        test_bus = EventBus()
        config = IngestionConfig(sse_buffer_size=50)
        manager = SSEManager(config=config, event_bus=test_bus)

        client = await manager.register_client(ip="127.0.0.1")
        # Drain initial snapshot
        while not client.queue.empty():
            client.queue.get_nowait()

        # Base snapshot
        snap1 = _make_test_snapshot(aspi=22624.31, turnover=9309760000.0)
        await manager.on_snapshot_accepted(snap1)
        # Drain any tick generated by snap1 (vs recovered disk snapshot)
        while not client.queue.empty():
            client.queue.get_nowait()

        # Next snapshot with ONLY aspi_value changed
        snap2 = _make_test_snapshot(aspi=22630.00, turnover=9309760000.0)
        await manager.on_snapshot_accepted(snap2)

        assert client.queue.qsize() == 1
        tick_event = client.queue.get_nowait()
        assert tick_event.event_type == "tick"
        assert "aspi_value" in tick_event.data
        assert tick_event.data["aspi_value"] == 22630.00
        # Turnover did not change, so it must NOT be in tick data diff
        assert "market_turnover" not in tick_event.data

        await manager.deregister_client(client)

    asyncio.run(_run())


def test_sse_manager_status_transition():
    """Verify market state or freshness transition emits a 'status' event."""
    async def _run():
        test_bus = EventBus()
        config = IngestionConfig(sse_buffer_size=50)
        manager = SSEManager(config=config, event_bus=test_bus)

        client = await manager.register_client(ip="127.0.0.1")
        while not client.queue.empty():
            client.queue.get_nowait()  # drain snapshot

        # Initialize snapshot with CLOSED
        snap_closed = _make_test_snapshot(raw_status="Market Closed", freshness=FreshnessState.CLOSED)
        await manager.on_snapshot_accepted(snap_closed)
        while not client.queue.empty():
            client.queue.get_nowait()

        # Transition to Regular Trading and LIVE
        snap_open = _make_test_snapshot(raw_status="Regular Trading", freshness=FreshnessState.LIVE)
        await manager.on_snapshot_accepted(snap_open)

        # Should have emitted a "status" event
        events = []
        while not client.queue.empty():
            events.append(client.queue.get_nowait())

        status_events = [e for e in events if e.event_type == "status"]
        assert len(status_events) >= 1
        assert status_events[0].data["freshness_state"] == "LIVE"

        await manager.deregister_client(client)

    asyncio.run(_run())


def test_sse_manager_last_event_id_replay():
    """Verify Last-Event-ID resumes missed events from ring buffer."""
    async def _run():
        test_bus = EventBus()
        config = IngestionConfig(sse_buffer_size=50)
        manager = SSEManager(config=config, event_bus=test_bus)

        # Client 1 connects and triggers some events
        c1 = await manager.register_client(ip="127.0.0.1")
        snap1_ev = c1.queue.get_nowait()
        first_seq = snap1_ev.seq

        # Broadcast 3 distinct ticks
        snap1 = _make_test_snapshot(aspi=22624.31)
        await manager.on_snapshot_accepted(snap1)
        snap2 = _make_test_snapshot(aspi=22628.00)
        await manager.on_snapshot_accepted(snap2)
        snap3 = _make_test_snapshot(aspi=22635.00)
        await manager.on_snapshot_accepted(snap3)

        await manager.deregister_client(c1)

        # Client 2 reconnects asking for events after first_seq
        c2 = await manager.register_client(ip="127.0.0.2", last_event_id=str(first_seq))
        replayed = []
        while not c2.queue.empty():
            replayed.append(c2.queue.get_nowait())

        assert len(replayed) >= 2
        # Verify all replayed events have seq > first_seq
        for r in replayed:
            assert r.seq > first_seq

        await manager.deregister_client(c2)

    asyncio.run(_run())


def test_sse_manager_backpressure_slow_client():
    """Verify that slow clients overflowing their queue drop oldest ticks without blocking."""
    async def _run():
        test_bus = EventBus()
        # Tiny queue of size 2 for testing
        config = IngestionConfig(sse_client_queue_size=2, sse_buffer_size=50)
        manager = SSEManager(config=config, event_bus=test_bus)

        client = await manager.register_client(ip="10.0.0.1")
        # Queue currently has 1 event (the snapshot)
        assert client.queue.qsize() == 1

        # Push 3 additional events without consumer draining
        e1 = SSEEvent(event_type="tick", data={"seq": 10}, seq=10, id="10", timestamp=datetime.now(timezone.utc))
        e2 = SSEEvent(event_type="tick", data={"seq": 11}, seq=11, id="11", timestamp=datetime.now(timezone.utc))
        e3 = SSEEvent(event_type="tick", data={"seq": 12}, seq=12, id="12", timestamp=datetime.now(timezone.utc))

        manager.broadcast(e1)
        manager.broadcast(e2)
        manager.broadcast(e3)

        # Queue must not exceed maxsize 2
        assert client.queue.qsize() <= 2
        assert client.dropped_events_count >= 1

        await manager.deregister_client(client)

    asyncio.run(_run())


def test_sse_manager_connection_limits():
    """Verify per-IP and max connection limits raise HTTP 429 and 503."""
    async def _run():
        test_bus = EventBus()
        config = IngestionConfig(sse_max_connections=3, sse_per_ip_cap=2)
        manager = SSEManager(config=config, event_bus=test_bus)

        # Register 2 clients from 192.168.1.100 (hits per-IP cap)
        c1 = await manager.register_client(ip="192.168.1.100")
        c2 = await manager.register_client(ip="192.168.1.100")

        # Third connection from same IP should raise 429
        with pytest.raises(HTTPException) as exc_info:
            await manager.register_client(ip="192.168.1.100")
        assert exc_info.value.status_code == 429

        # Connection from different IP should succeed (hits global max=3)
        c3 = await manager.register_client(ip="192.168.1.101")
        assert manager.active_connection_count == 3

        # Fourth connection from any IP should raise 503 (max reached)
        with pytest.raises(HTTPException) as exc_info:
            await manager.register_client(ip="192.168.1.102")
        assert exc_info.value.status_code == 503

        await manager.deregister_client(c1)
        await manager.deregister_client(c2)
        await manager.deregister_client(c3)

    asyncio.run(_run())


def test_sse_heartbeat_generator():
    """Verify generator yields initial snapshot and heartbeat event after timeout."""
    async def _run():
        test_bus = EventBus()
        config = IngestionConfig(sse_heartbeat_interval_seconds=0.1, sse_buffer_size=50)
        manager = SSEManager(config=config, event_bus=test_bus)
        client = await manager.register_client(ip="127.0.0.1")

        class MockRequest:
            async def is_disconnected(self):
                return False

        gen = manager.stream_events(client, MockRequest())
        # First chunk is initial snapshot
        first_chunk = await gen.__anext__()
        assert "event: snapshot" in first_chunk

        # Next chunk after 0.1s heartbeat interval is heartbeat
        hb_chunk = await gen.__anext__()
        assert "event: heartbeat" in hb_chunk
        assert "timestamp" in hb_chunk

        await manager.deregister_client(client)

    asyncio.run(_run())


