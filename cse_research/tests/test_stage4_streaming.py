def test_sse_event_encoding():
    """Verify SSEEvent encodes strictly according to the W3C text/event-stream specification."""
    event = SSEEvent(
        event_type="tick",
        data={"aspi_value": 22650.0, "seq": 42},
        seq=42,
        id="42",
        timestamp=datetime.now(timezone.utc),
    )
    encoded = event.encode()
    assert encoded.startswith("id: 42\n")
    assert "event: tick\n" in encoded
    assert 'data: {"aspi_value": 22650.0, "seq": 42}\n\n' in encoded


