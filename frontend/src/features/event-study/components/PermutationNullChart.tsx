import { useMemo } from 'react';
import { EChart } from '@/components/charts';
import { Card, CardHeader, CardTitle, CardContent } from '@/components/ui/Card';
import { Badge } from '@/components/ui/Badge';
import { buildPermutationHistogramOption } from '../utils/chart-options';
import type { PermutationDistribution } from '../types';

export interface PermutationNullChartProps {
  distribution?: PermutationDistribution;
  isLoading?: boolean;
}

export function PermutationNullChart({ distribution, isLoading }: PermutationNullChartProps) {
  const chartOption = useMemo(() => {
    return buildPermutationHistogramOption(distribution);
  }, [distribution]);

  if (isLoading || !distribution) {
    return (
      <Card className="h-80 animate-pulse">
        <CardContent className="h-full" />
      </Card>
    );
  }

  return (
    <Card className="border-border/80 shadow-sm">
      <CardHeader className="border-border/40 flex flex-row flex-wrap items-center justify-between gap-2 border-b pb-3">
        <div>
          <div className="flex items-center gap-2">
            <CardTitle className="text-base font-semibold">
              Permutation Placebo Null Distribution
            </CardTitle>
            <Badge variant="outline" className="text-xs">
              {distribution.draws?.toLocaleString() ?? '10,000'} Non-Event Draws
            </Badge>
          </div>
          <p className="text-muted-foreground mt-0.5 text-xs">
            Empirical null distribution ($H_0$) generated by pseudo-event sampling across 30+ years
            of non-event trading dates.
          </p>
        </div>
        <div className="flex items-center gap-2 font-mono text-xs">
          <span className="text-muted-foreground">Observed CAAR:</span>
          <span className="text-primary font-bold">
            {distribution.observed_value > 0
              ? `+${distribution.observed_value}%`
              : `${distribution.observed_value}%`}
          </span>
          <span className="text-muted-foreground">(p = {distribution.p_value})</span>
        </div>
      </CardHeader>

      <CardContent className="p-4">
        <div className="w-full">
          <EChart option={chartOption} height={340} />
        </div>
      </CardContent>
    </Card>
  );
}
